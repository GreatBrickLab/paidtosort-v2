// Builds pages-bundle/scanner.mjs (the prebuilt Pages bundle, ADR 0008) and pages-bundle/THIRD_PARTY_NOTICES.md
// (licenses of every npm package inside the bundle). Deterministic: same lockfile → same bytes.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const result = await build({
  entryPoints: ['src/pages.ts'], bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', mainFields: ['module', 'main'],
  minify: true, legalComments: 'none', metafile: true, outfile: 'pages-bundle/scanner.mjs',
  banner: { js: '// GENERATED by npm run bundle:pages from apps/scanner/src. Do not edit; rebuild. Third-party licenses: THIRD_PARTY_NOTICES.md' },
});

const pkgs = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  const m = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input);
  if (m) pkgs.set(m[1], join('node_modules', m[1]));
}
const out = ['# Third-party notices for pages-bundle/scanner.mjs', '',
  'The bundle includes the following open-source packages. Their license texts follow.', ''];
for (const name of [...pkgs.keys()].sort()) {
  const dir = pkgs.get(name);
  const pj = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const lic = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  out.push(`## ${name} ${pj.version} (${pj.license ?? 'see license text'})`, '');
  out.push(lic && existsSync(join(dir, lic)) ? '```\n' + readFileSync(join(dir, lic), 'utf8').trim() + '\n```' : `License: ${pj.license ?? 'unknown'} (no license file shipped in the package)`, '');
}
writeFileSync('pages-bundle/THIRD_PARTY_NOTICES.md', out.join('\n').trimEnd() + '\n');
console.log(`bundle: pages-bundle/scanner.mjs, notices for ${pkgs.size} packages: ${[...pkgs.keys()].sort().join(', ')}`);
